#!/usr/bin/env bash
# Build the vendored CLI tools as fully static binaries and install them into
# rootfs/usr/local/bin (which ends up on PATH ahead of everything else).
#
# Requirements: podman (uses the local alpine:3.24 image; pulls it if missing).
# Sources must already be vendored: run scripts/fetch-cli-sources.sh first.
#
# Usage: scripts/build-cli-tools.sh [--jobs N] [--no-install]
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
src="$repo_root/sources"
out="$repo_root/.cache/cli-tools-out"
jobs=$(nproc 2>/dev/null || echo 4)
install=1

while [ $# -gt 0 ]; do
    case "$1" in
        --jobs) jobs="$2"; shift 2 ;;
        --no-install) install=0; shift ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done

[ -d "$src" ] && [ -n "$(ls -A "$src" 2>/dev/null)" ] || {
    echo "sources/ is empty - run scripts/fetch-cli-sources.sh first" >&2
    exit 1
}

rm -rf "$out"
mkdir -p "$out"

echo "== preparing builder image (alpine:3.24) =="
podman build -q -t tacolinux-cli-builder:latest \
    -f "$repo_root/scripts/cli-tools/Containerfile" \
    "$repo_root/scripts/cli-tools" >/dev/null

echo "== building static CLI tools (jobs=$jobs) =="
podman run --rm \
    -e "JOBS=$jobs" -e SKIP_APK=1 \
    -v "$src:/src:ro,z" \
    -v "$out:/out:z" \
    -v "$repo_root/scripts/cli-tools:/build:ro,z" \
    tacolinux-cli-builder:latest bash /build/build-inner.sh

built="$out/static/bin"
count=$(find "$built" -maxdepth 1 -type f | wc -l)
echo
echo "== static binaries built: $count =="
if [ "$count" -eq 0 ]; then
    echo "nothing was built - check $out/logs" >&2
    exit 1
fi

if [ "$install" -eq 1 ]; then
    dest="$repo_root/rootfs/usr/local/bin"
    mkdir -p "$dest"
    installed=0
    while IFS= read -r f; do
        b=$(basename "$f")
        install -m755 "$f" "$dest/$b"
        installed=$((installed + 1))
    done < <(find "$built" -maxdepth 1 -type f)
    echo "== installed $installed binaries into rootfs/usr/local/bin =="

    # convenience aliases that upstream normally provides via symlinks
    for alias_pair in "unzstd:zstd" "zstdcat:zstd" "zstdmt:zstd" "bunzip2:bzip2" "bzcat:bzip2"; do
        alias_name=${alias_pair%%:*}
        target=${alias_pair##*:}
        [ -x "$dest/$target" ] && ln -sfn "$target" "$dest/$alias_name"
    done

    # record what shipped
    mkdir -p "$repo_root/rootfs/usr/local/share/tacolinux"
    head -n1 "$repo_root/scripts/cli-tools/apps.tsv" >/dev/null
    {
        echo "# CLI tools bundled in TacoLinux (statically linked, built from sources/)"
        echo "# generated by scripts/build-cli-tools.sh - do not edit by hand"
        find "$built" -maxdepth 1 -type f -printf '%f\n' | sort
    } > "$repo_root/rootfs/usr/local/share/tacolinux/cli-tools.txt"
fi

cp -f "$out/BUILD-REPORT.txt" "$repo_root/.cache/cli-tools-build-report.txt" 2>/dev/null || true
echo "report: .cache/cli-tools-build-report.txt, logs: .cache/cli-tools-out/logs/"
